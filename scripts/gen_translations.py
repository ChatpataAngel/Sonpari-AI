def build_doc(rules, reflections, fallbacks, proactive):
    return {
        "rules": rules,
        "reflection_rules": reflections,
        "fallbacks": fallbacks,
        "proactive": proactive,
    }


def main():
    from scripts._hinglish_rules import (
        HINGLISH_RULES, HINGLISH_REFLECTIONS, HINGLISH_FALLBACKS, HINGLISH_PROACTIVE,
    )
    src = yaml.safe_load(RULES.read_text(encoding="utf-8"))
    src_rule_ids = [str(r["id"]) for r in src["rules"]]
    src_patterns = [item["pattern"] for item in src.get("reflection_rules", [])]

    docs = {
        "hi": build_doc(HI_RULES, HI_REFLECTIONS, HI_FALLBACKS, HI_PROACTIVE),
        "hinglish": build_doc(HINGLISH_RULES, HINGLISH_REFLECTIONS,
                              HINGLISH_FALLBACKS, HINGLISH_PROACTIVE),
    }

    errors = []
    for lang, doc in docs.items():
        # Every rule id in the English source must have a translation entry.
        missing_rules = [rid for rid in src_rule_ids if rid not in doc["rules"]]
        if missing_rules:
            errors.append(f"[{lang}] missing rule translations: {missing_rules}")
        # Every reflection pattern must be translated.
        missing_refl = [p for p in src_patterns if p not in doc["reflection_rules"]]
        if missing_refl:
            errors.append(f"[{lang}] missing reflection translations: {missing_refl}")
        # Response counts should match the English source.
        for r in src["rules"]:
            rid = str(r["id"])
            if rid in doc["rules"] and len(doc["rules"][rid]) != len(r["responses"]):
                errors.append(
                    f"[{lang}] rule '{rid}' has {len(doc['rules'][rid])} responses, "
                    f"expected {len(r['responses'])}"
                )
        if len(doc["fallbacks"]) != len(src.get("fallbacks", [])):
            errors.append(
                f"[{lang}] fallbacks: {len(doc['fallbacks'])} vs expected {len(src.get('fallbacks', []))}"
            )
        if len(doc["proactive"]) != len(src.get("proactive", [])):
            errors.append(
                f"[{lang}] proactive: {len(doc['proactive'])} vs expected {len(src.get('proactive', []))}"
            )

    if errors:
        print("VALIDATION FAILED:")
        for e in errors:
            print("  -", e)
        sys.exit(1)

    for lang, doc in docs.items():
        out = RULES.with_name(RULES.stem + "." + lang + RULES.suffix)
        with out.open("w", encoding="utf-8") as fh:
            yaml.safe_dump(doc, fh, allow_unicode=True, sort_keys=False, width=1000)
        n = sum(len(v) for v in doc["rules"].values())
        print(f"wrote {out} ({len(doc['rules'])} rules, {n} responses)")


if __name__ == "__main__":
    main()
