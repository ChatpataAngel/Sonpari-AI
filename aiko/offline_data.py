# -*- coding: utf-8 -*-
"""Loader for Aiko's offline JSON content files.

These files are generated by ChatGPT via tools/generate_json_content.py ("promptresearch").
They serve:

  1. friendly_chat.json  -> for PASS-CODE users (and known non-owner users)
                             Treated as FRIEND, NOT her BF. Normal, casual,
                             balcony-style chat. NO relationship/lover talk.
  2. offline_content.json -> general offline fallback content (greetings,
                             questions, daily check, feelings check)
  3. offline_boundaries.json -> safety/boundary phrases: how to decline
                             flirt, how to redirect, safety lines, end-chat lines

All content is OFFLINE: no network, no database, no API calls.
"""
from __future__ import annotations

import json
import random
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT_DIR = ROOT / "aiko" / "data" / "content"

_LOADED = {}
_originals = {}


def _load_file(name: str) -> dict:
    """Load a JSON content file. Return {} if missing/corrupt."""
    path = CONTENT_DIR / f"{name}.json"
    try:
        if path.exists():
            with open(path, "r", encoding="utf-8") as f:
                return json.load(f)
    except (OSError, json.JSONDecodeError):
        pass
    return {}


def get_friendly_chat() -> dict:
    """Friendly chat content for friends (pass-code users)."""
    if "friendly_chat" not in _LOADED:
        _LOADED["friendly_chat"] = _load_file("friendly_chat")
    return _LOADED["friendly_chat"]


def get_offline_content() -> dict:
    """General offline fallback content."""
    if "offline_content" not in _LOADED:
        _LOADED["offline_content"] = _load_file("offline_content")
    return _LOADED["offline_content"]


def get_offline_boundaries() -> dict:
    """Boundary/safety content."""
    if "offline_boundaries" not in _LOADED:
        _LOADED["offline_boundaries"] = _load_file("offline_boundaries")
    return _LOADED["offline_boundaries"]


def pick(segment: str, lang: str = "hinglish") -> str | None:
    """Pick a random response from a segment, with language fallback."""
    if not segment:
        return None
    lang = lang if lang in {"hinglish", "hi", "en"} else "hinglish"
    data = get_friendly_chat().get(segment) or get_offline_content().get(segment)
    if not data:
        return None
    if lang in data:
        return random.choice(data[lang])
    # Fallback: pick first available language
    for l in data:
        return random.choice(data[l])
    return None


def pick_boundary(segment: str, lang: str = "hinglish") -> str | None:
    """Pick from boundary content (decline, redirect, safety, end)."""
    if not segment:
        return None
    lang = lang if lang in {"hinglish", "hi", "en"} else "hinglish"
    data = get_offline_boundaries().get(segment)
    if not data:
        return None
    if lang in data:
        return random.choice(data[lang])
    for l in data:
        return random.choice(data[l])
    return None


def get_all_segments(lang: str = "hinglish") -> list[tuple[str, str]]:
    """Return a list of (segment_name, pick_string) for all friendly content."""
    out = []
    for seg in get_friendly_chat():
        txt = pick(seg, lang)
        if txt:
            out.append((seg, txt))
    for seg in get_offline_content():
        txt = pick(seg, lang)
        if txt:
            out.append((seg, txt))
    return out


def reset_cache() -> None:
    """Clear the loaded cache (useful for testing / dynamic reload)."""
    _LOADED.clear()
    _originals.clear()
